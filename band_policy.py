"""Configurable percentile bands + data-quality gates for the lookup engine.

Enhancement B — Percentile Width Configurable.

The per-crop lookup bands (ML/crop_bands.json) were fixed at the 40th-60th
percentile of each crop's 100 dataset rows. For N=100 that width is
statistically unstable (a handful of central samples move the edges) and
narrower than the peer-reviewed "optimal zone" convention (the interquartile
range, 25th-75th, or the middle third, 33rd-67th).

This module makes the percentile width a *policy* with per-nutrient overrides
and a coefficient-of-variation (CV) quality gate, mirroring the recommended
production block:

    default_statistical_bounds:
        stable_middle_third  = [33, 67]
        standard_iqr_optimal = [25, 75]
    data_situation_overrides:
        high_variance_nutrients (P)  = [35, 65]
        logarithmic_scale_sensitive (pH) = [40, 60]
    data_quality_gates:
        minimum_allowed_cv_percentage = 15.0
        action_on_fail = FLAG_AS_HARDCODED_OR_SYNTHETIC

It is ADDITIVE and backward compatible: the default policy is "legacy" — the
exact 40th-60th percentile used before — so ML/crop_bands.json and every
consumer (engine advice, /api/crops bands) stay byte-for-byte unchanged.
Selecting another policy is an explicit opt-in via the BAND_PERCENTILE_POLICY
environment variable or the ML/crop_bands.py --policy flag.

Scope note: this calibrates the deterministic *lookup/advice* engine, not the
RandomForest training labels. Training data is generated by
tools/generate_zone_dataset.py from the Ethiopian zone bands in
ethiopian_standards.py. Turning the percentile policy on changes the advice
bands, never the trained model.
"""

from __future__ import annotations

import os

COLS = ("N", "P", "K", "ph")

DEFAULT_POLICY = "legacy"
RECOMMENDED_POLICY = "recommended"

# Data-quality gate (coefficient of variation, %). Real field-collected
# Ethiopian soil nutrients rarely show CV < 15-20%; a tighter spread points
# to synthetic generation or a hard-coded/default lookup column.
MIN_ALLOWED_CV_PCT = 15.0
CV_FAIL_ACTION = "FLAG_AS_HARDCODED_OR_SYNTHETIC"

# Percentile fractions (0-1). "legacy" reproduces the original 40/60 split.
POLICIES = {
    "legacy": {"default": (0.40, 0.60), "columns": {}},
    "middle_third": {"default": (0.33, 0.67), "columns": {}},
    "iqr": {"default": (0.25, 0.75), "columns": {}},
    "recommended": {
        "default": (0.25, 0.75),
        "columns": {"P": (0.35, 0.65), "ph": (0.40, 0.60)},
    },
}

POLICY_ENV = "BAND_PERCENTILE_POLICY"


def policy_names():
    """Sorted list of valid policy names."""
    return sorted(POLICIES)


def is_valid_policy(policy):
    return policy in POLICIES


def active_policy():
    """Policy selected by the environment, else the safe legacy default."""
    value = os.getenv(POLICY_ENV, "").strip().lower()
    return value if value in POLICIES else DEFAULT_POLICY


def resolve(col, policy=None):
    """(lo, hi) percentile fractions for a column under a policy.

    Unknown columns fall back to the policy default band; unknown policies
    fall back to the legacy default. Never raises.
    """
    name = policy if policy in POLICIES else DEFAULT_POLICY
    spec = POLICIES[name]
    return tuple(spec["columns"].get(col, spec["default"]))


def policy_definition(policy=None):
    """Human-readable shape of a policy (the production block, made valid)."""
    name = policy if policy in POLICIES else DEFAULT_POLICY
    return {
        "policy": name,
        "default_statistical_bounds": {
            "stable_middle_third": [33, 67],
            "standard_iqr_optimal": [25, 75],
        },
        "resolved_percentiles": {col: list(resolve(col, name)) for col in COLS},
        "data_quality_gates": {
            "minimum_allowed_cv_percentage": MIN_ALLOWED_CV_PCT,
            "action_on_fail": CV_FAIL_ACTION,
        },
    }


def percentile_band(values, col=None, policy=None):
    """(lo, hi) values at the policy's percentiles for a numeric sequence."""
    import numpy as np

    arr = np.asarray(list(values), dtype=float)
    lo_q, hi_q = resolve(col, policy)
    lo, hi = np.quantile(arr, [lo_q, hi_q])
    return float(lo), float(hi)


def coefficient_of_variation(values):
    """CV in percent (std / mean * 100); 0.0 when undefined (mean 0/empty)."""
    import numpy as np

    arr = np.asarray(list(values), dtype=float)
    if arr.size == 0:
        return 0.0
    mean = float(arr.mean())
    if mean == 0.0:
        return 0.0
    return float(arr.std(ddof=1)) / abs(mean) * 100.0 if arr.size > 1 else 0.0


def data_quality(values, col=None, min_cv_pct=None):
    """CV quality gate for one column: flags implausibly tight spreads.

    Returns {cv_pct, min_allowed_cv_pct, flag, action}. `flag` is True when
    the spread is below the gate, i.e. the column looks hard-coded/synthetic.
    """
    gate = MIN_ALLOWED_CV_PCT if min_cv_pct is None else float(min_cv_pct)
    cv = round(coefficient_of_variation(values), 2)
    flag = cv < gate
    return {
        "cv_pct": cv,
        "min_allowed_cv_pct": gate,
        "flag": flag,
        "action": CV_FAIL_ACTION if flag else None,
    }
