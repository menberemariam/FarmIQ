def normalize_lang(raw):
    """Map any common spelling of a language code to the canonical key.

    Accepts "am", "amh", "am-ET", "አማርኛ" -> "am"; "om", "orm", "om-ET",
    "Afaan Oromoo", "Oromiffa", "Qubee" -> "om". Unknown -> "en".
    """
    if not isinstance(raw, str):
        return "en"
    value = raw.strip().lower()
    if value in ("am", "amh", "am-et", "amharic", "አማርኛ"):
        return "am"
    if value in ("om", "orm", "om-et", "oromo", "afaan oromoo",
                 "afaan oromia", "oromiffa", "qubee"):
        return "om"
    return "en"


def normalize_amharic(text):
    """Normalize Amharic text: NFC, canonical orthography, BOM/zero-width and
    whitespace cleanup. Applied at storage/matching boundaries."""
    if not isinstance(text, str):
        return text
    text = unicodedata.normalize("NFC", text)
    text = "".join(AMHARIC_ORTHO_MAP.get(ch, ch) for ch in text)
    text = text.replace("\ufeff", "").replace("\u200b", "").replace("\u200c", "")
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


def normalize_qubee(text):
    """Normalize Afaan Oromoo text: NFC (composes Qubee vowel diacritics),
    BOM/zero-width stripping and whitespace cleanup. Applied at LLM-output
    boundaries only (never to stored user text); unlike Amharic there is no
    historic-to-modern glyph mapping to apply."""
    if not isinstance(text, str):
        return text
    text = unicodedata.normalize("NFC", text)
    text = text.replace("﻿", "").replace("​", "").replace("‌", "")
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


